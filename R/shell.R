# ---------------------------------------------------------------------------
# Shell stage orchestration.
#
# The upstream stages (BAM merge, HaplotypeCaller, joint genotyping, BED
# conversion, bedtools intersection) stay as shell scripts, because that is
# where the tools live and because they need a scheduler. What changes is
# that there is now one script per stage, parameterised, instead of the
# original `3_RUN.sh`, `3_RUN_Apr16.sh`, `3_RUN_apr18.sh`, `3_RUN_apr22.sh`,
# `3_RUN_apr24.sh` family -- five copies of the same script differing only in
# the sample list and the date in the log path.
#
# R renders the template with a config block prepended and either runs it or
# hands you a submittable file.
# ---------------------------------------------------------------------------

#' List the bundled shell stages
#'
#' @return A `data.frame` of stage scripts and what they do.
#' @export
#' @examples
#' pgvis_stages()
pgvis_stages <- function() {
  d <- system.file("bash", package = "PGViS")
  f <- sort(list.files(d, pattern = "^\\d\\d_.*\\.sh$"))
  desc <- c(
    "01_merge_bams.sh"      = "Merge replicate BAMs per patient and tissue",
    "02_call_gvcf.sh"       = "GATK HaplotypeCaller, per sample per chromosome",
    "03_combine_gvcf.sh"    = "CombineGVCFs / GenomicsDBImport across the cohort",
    "04_genotype_filter.sh" = "GenotypeGVCFs, hard filter, normalise, split multiallelics",
    "05_vcf2bed.sh"         = "VCF to BED with AC/AF/AN and per-variant carrier lists",
    "06_intersect.sh"       = "Intersect variants with regulatory regions and dbSNP",
    "07_predict.sh"         = "Run DNABERT predictions from a local checkout"
  )
  data.frame(stage = f,
             description = unname(desc[f]),
             path = file.path(d, f),
             stringsAsFactors = FALSE)
}

#' Render a bundled shell stage with your configuration
#'
#' Prepends a generated variable block to the template, so the templates
#' themselves contain no site-specific paths.
#'
#' @param stage File name from [pgvis_stages()].
#' @param vars Named list of shell variables to define.
#' @param cfg Optional [pgvis_config()]. Supplies output paths, thread count,
#'   and SLURM directives.
#' @param outfile Where to write. Defaults to `cfg$dirs$logs`.
#' @param submit Submit via the configured scheduler, run locally, or neither.
#'   `NA` (the default from the wrappers) writes the script and stops.
#' @param array Optional `SLURM_ARRAY` specification, e.g. `"1-48%12"`.
#' @return Path to the rendered script, invisibly.
#' @export
pgvis_render_script <- function(stage, vars = list(), cfg = NULL,
                                outfile = NULL, submit = FALSE, array = NULL) {
  tpl <- system.file("bash", stage, package = "PGViS")
  if (!nzchar(tpl)) stop("Unknown stage '", stage, "'. See pgvis_stages().",
                         call. = FALSE)
  lines <- readLines(tpl, warn = FALSE)

  if (!is.null(cfg)) {
    .assert_config(cfg)
    vars <- utils::modifyList(list(
      PGVIS_ROOT = cfg$root,
      REF_FASTA  = cfg$reference_fasta %||% "",
      DBSNP_DIR  = cfg$dbsnp_dir %||% "",
      THREADS    = cfg$threads,
      LOG_DIR    = cfg$dirs$logs,
      CHROMS     = paste(cfg$chromosomes, collapse = " "),
      COHORTS    = paste(cfg$cohorts, collapse = " ")
    ), vars)
  }

  header <- c(
    "#!/usr/bin/env bash",
    "# ---- generated by PGViS::pgvis_render_script(); edit the config below, not the body ----",
    sprintf("# generated: %s", format(Sys.time())),
    .slurm_directives(cfg, array),
    "set -euo pipefail",
    "",
    vapply(names(vars), function(k) sprintf("%s=%s", k, shQuote(as.character(vars[[k]]))),
           character(1), USE.NAMES = FALSE),
    if (length(vars)) paste("export", paste(names(vars), collapse = " ")) else character(0),
    "# ---- end generated block ----",
    ""
  )
  body <- lines[!grepl("^#!/", lines)]

  log_dir <- if (is.null(cfg)) tempdir() else cfg$dirs$logs
  outfile <- outfile %||% file.path(log_dir, paste0(sub("\\.sh$", "", stage), ".run.sh"))
  dir.create(dirname(outfile), recursive = TRUE, showWarnings = FALSE)
  writeLines(c(header, body), outfile)
  Sys.chmod(outfile, "0755")
  .msg("Rendered ", stage, " -> ", outfile)

  if (isTRUE(submit)) pgvis_submit(outfile, cfg)
  invisible(outfile)
}

.slurm_directives <- function(cfg, array = NULL) {
  if (is.null(cfg) || cfg$scheduler != "slurm") return(character(0))
  s <- cfg$slurm
  d <- c(
    "#SBATCH --job-name=pgvis",
    sprintf("#SBATCH --output=%s/%%A_%%a.out", cfg$dirs$logs),
    sprintf("#SBATCH --error=%s/%%A_%%a.err",  cfg$dirs$logs),
    sprintf("#SBATCH --cpus-per-task=%d", s$cpus_per_task %||% cfg$threads),
    sprintf("#SBATCH --mem=%s",  s$mem  %||% "32G"),
    sprintf("#SBATCH --time=%s", s$time %||% "24:00:00")
  )
  if (!is.null(s$partition)) d <- c(d, sprintf("#SBATCH --partition=%s", s$partition))
  if (!is.null(s$account))   d <- c(d, sprintf("#SBATCH --account=%s", s$account))
  if (!is.null(array))       d <- c(d, sprintf("#SBATCH --array=%s", array))
  d
}

#' Run or submit a rendered stage
#'
#' @param script Path from [pgvis_render_script()].
#' @param cfg A [pgvis_config()]; `cfg$scheduler` decides between `sbatch`
#'   and a local `bash` call.
#' @return The command's exit status, invisibly.
#' @export
pgvis_submit <- function(script, cfg = NULL) {
  sched <- if (is.null(cfg)) "none" else cfg$scheduler
  if (sched == "slurm") {
    .need_bin("sbatch")
    .msg("sbatch ", script)
    status <- system2("sbatch", shQuote(script))
  } else {
    .msg("bash ", script)
    status <- system2("bash", shQuote(script))
  }
  if (status != 0) warning("Stage exited with status ", status, call. = FALSE)
  invisible(status)
}
